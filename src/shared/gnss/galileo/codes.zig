pub const e1_chips = 4092;
pub const cs100_chips = @bitSizeOf(@TypeOf(cs100_codes[0]));
const bytes_per_code = 512;

pub fn e1(sat: SatId, pilot: bool, out: *[e1_chips]u8) void {
    const index: usize = @as(usize, if (pilot) 50 else 0) + sat.index;
    const bytes = blobs.e1_codes.bytes[index * bytes_per_code ..][0..bytes_per_code];
    for (out, 0..) |*chip, j| chip.* = (bytes[j / 8] >> @intCast(7 - j % 8)) & 1;
}

