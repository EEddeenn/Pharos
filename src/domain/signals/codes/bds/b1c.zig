const l10243 = weil.Legendre(10243);
const l3607 = weil.Legendre(3607);

const Weil = struct { w: u14, p: u14 };

const b1c_secondary: [63][b1c_secondary_chips]u1 = blk: {
    @setEvalBranchQuota(1_000_000);
    var t: [63][b1c_secondary_chips]u1 = undefined;
    for (b1c_secondary_codes, &t) |c, *code| {
        for (code, 0..) |*chip, i| chip.* = l3607.weil((i + c.p - 1) % 3607, c.w);
    }
    break :blk t;
};

pub fn b1c(sat: SatId, pilot: bool, out: *[b1c_chips]u8) void {
    const c = (if (pilot) b1c_pilot else b1c_data)[sat.index];
    for (out, 0..) |*chip, i| chip.* = l10243.weil(@intCast((i + c.p - 1) % 10243), c.w);
}

pub fn b1cSecondary(sat: SatId) *const [b1c_secondary_chips]u1 {
    return &b1c_secondary[sat.index];
}

